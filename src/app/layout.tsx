import type { Metadata, Viewport } from "next";
import { Geist_Mono, Inter } from "next/font/google";

import { Suspense } from "react";

import { NavProgress } from "@/components/nav-progress";
import { Toaster } from "@/components/toaster";
import { STARTUP_IMAGES } from "@/lib/generated/startup-images";
import "./globals.css";

/**
 * The type is the platform's own on Apple devices and Inter everywhere else.
 *
 * SF Pro may not be served as a web font — its licence covers Apple platforms
 * only — but `-apple-system` asks the OS for it, so an iPhone or a Mac reads
 * this app in the face every other app on it uses. Inter is the stand-in for
 * the rest: the closest open face to SF, and with `cv11` (single-storey a) and
 * `ss01` (open digits) switched on in globals.css it sits closer still. The
 * stack itself lives in `--font-sans`, so this only has to load Inter.
 */
const inter = Inter({
  variable: "--font-inter",
  subsets: ["latin", "cyrillic"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

/**
 * The tab, the home screen and the browser chrome.
 *
 * `icons` is declared here rather than by dropping `icon.svg` into `app/`,
 * which is the other way Next.js will do this. The file convention scatters
 * the brand across two places — an `app/icon.svg` for the tab and a
 * `public/` copy for everything with no bundler (an email header, a PDF
 * guide) — and the pair drifted once already: the retired `app/icon.svg`
 * carried an orange capital F, which is neither the letter nor the colour the
 * wordmark uses. One set of files under `public/brand/`, named here, cannot
 * drift.
 *
 * Two icons because they are read by different things: `favicon.ico` is the
 * 32px raster every browser still asks for first, `icon.svg` is the one that
 * stays sharp on a retina tab and in a bookmark bar.
 */
export const metadata: Metadata = {
  title: "freshlog",
  description: "Track mentoring hours, sessions and meetings.",
  icons: {
    icon: [
      { url: "/brand/favicon.ico", sizes: "32x32" },
      { url: "/brand/icon.svg", type: "image/svg+xml", sizes: "any" },
    ],
    apple: { url: "/brand/apple-touch-icon.png", sizes: "180x180" },
  },
  /*
   * iOS honours its own meta tags rather than the manifest, so standalone mode
   * is declared twice — `appleWebApp` here, `display: "standalone"` in
   * manifest.ts for everything else.
   *
   * `statusBarStyle: "default"` gives a light status strip with dark text,
   * which disappears into the (white, `bg-surface`) header in light mode and
   * stays a readable clock in dark mode. `black-translucent` would slide the
   * page UNDER the clock and print it in white — invisible on a white header.
   * The style is locked at first launch and cannot follow the theme, so the
   * choice has to be the one that is never invisible.
   *
   * `startupImage` is generated by scripts/generate-brand-assets.mjs — iOS
   * matches a launch image to an exact logical size and pixel ratio, and a
   * device with no match simply launches on white.
   */
  appleWebApp: {
    capable: true,
    title: "freshlog",
    statusBarStyle: "default",
    startupImage: [...STARTUP_IMAGES],
  },
};

/**
 * `theme-color` tints the phone's address bar, which sits directly above this
 * app's header — and that header is `bg-surface` under a `line` hairline. So
 * the bar is `surface` too, and the chrome reads as one continuous white
 * surface. Brand blue up there would be a wash, which is the thing §5.6 rule 7
 * took out of every page below it.
 *
 * On `viewport` and not on `metadata`: `metadata.themeColor` is deprecated as
 * of Next 14 and warns during the build.
 */
export const viewport: Viewport = {
  themeColor: [
    { media: "(prefers-color-scheme: light)", color: "#ffffff" },
    { media: "(prefers-color-scheme: dark)", color: "#121417" },
  ],
  /*
   * `cover` lets the page run edge to edge behind the notch and the home
   * indicator, which is the ONLY thing that makes `env(safe-area-inset-*)`
   * non-zero — the tab bar's `pb-[env(safe-area-inset-bottom)]` was written
   * for it and measured 0 without it.
   *
   * `resizes-content` (Chrome/Android) shrinks the layout viewport when the
   * keyboard opens, so the fixed bottom bar lands above it rather than under
   * it. iOS ignores the hint and overlays the keyboard instead — the tab bar
   * detects that and steps out of the way itself.
   */
  viewportFit: "cover",
  interactiveWidget: "resizes-content",
};

/**
 * Set the theme BEFORE the first paint.
 *
 * Inline and synchronous on purpose: anything deferred — a `useEffect`, a
 * module the bundler splits out — runs after the browser has already painted,
 * so a reader who chose dark gets a full white page first. That flash is the
 * whole reason this is a `<script>` in the document and not a component.
 *
 * A stored choice wins; with none, the operating system decides. The table
 * density rides along for the same reason — a roster that paints at one row
 * height and jumps to another is the same flash in a different shape. Wrapped in
 * try/catch because reading `localStorage` throws outright in a browser set to
 * block site data, and a theme is not worth a blank page.
 */
const THEME_SCRIPT = `(function(){try{var t=localStorage.getItem("theme");if(t!=="dark"&&t!=="light"){t=window.matchMedia("(prefers-color-scheme: dark)").matches?"dark":"light"}document.documentElement.dataset.theme=t;if(localStorage.getItem("rail")==="collapsed"){document.documentElement.dataset.rail="collapsed"}var d=localStorage.getItem("density");if(d==="compact"||d==="comfortable"){document.documentElement.dataset.density=d}}catch(e){}})()`;

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  return (
    <html
      lang="en"
      className={`${inter.variable} ${geistMono.variable} h-full antialiased`}
      suppressHydrationWarning
    >
      <head>
        {/* Next emits only the standard `mobile-web-app-capable`, which iOS
            learned at 16.4 — the prefixed name is what older iPhones read. */}
        <meta name="apple-mobile-web-app-capable" content="yes" />
        <script dangerouslySetInnerHTML={{ __html: THEME_SCRIPT }} />
      </head>
      <body className="min-h-full flex flex-col">
        {/* Suspense: it reads the search params, which a static render
            cannot know — without a boundary that bails the whole root out. */}
        <Suspense fallback={null}>
          <NavProgress />
        </Suspense>
        {children}
        <Toaster />
      </body>
    </html>
  );
}
