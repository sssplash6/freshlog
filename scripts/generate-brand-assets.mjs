/**
 * Renders every raster the brand needs out of the two SVGs in public/brand/.
 *
 * The PWA install layer wants real PNGs, not the SVG: Android launchers read
 * the manifest icons, iOS composites apple-touch-icon for the home screen and
 * apple-touch-startup-image while the page loads. All of it comes from
 * icon.svg — one source, so the favicon, the home screen and the splash
 * cannot drift apart the way the retired app/icon.svg once did.
 *
 *   node scripts/generate-brand-assets.mjs
 *
 * Writes PNGs into public/brand/ and src/lib/generated/startup-images.ts —
 * the array layout.tsx feeds appleWebApp.startupImage, regenerated here so a
 * size is never declared for a file that does not exist.
 *
 * sharp is a Next.js transitive dependency; no install needed.
 */
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const ROOT = path.dirname(fileURLToPath(import.meta.url)) + "/..";
const BRAND = `${ROOT}/public/brand`;
const ICON = `${BRAND}/icon.svg`;

const BRAND_BLUE = "#124b84"; // globals.css --color-brand / lib/brand.ts
const SURFACE = "#ffffff"; // --color-surface — the splash ground

/** icon.svg rendered N px square (rounded square + white f, transparent corners). */
const iconPng = (size) =>
  sharp(ICON, { density: 600 }).resize(size).png().toBuffer();

/** Full-bleed blue square, the mark at 78% — inside the maskable safe zone. */
async function maskable(size) {
  const icon = await iconPng(Math.round(size * 0.78));
  return sharp({
    create: {
      width: size,
      height: size,
      channels: 4,
      background: BRAND_BLUE,
    },
  })
    .composite([{ input: icon, gravity: "center" }])
    .png()
    .toBuffer();
}

/** White launch image, mark centred at ~25% of the short edge. */
async function splash(w, h) {
  const icon = await iconPng(Math.round(Math.min(w, h) * 0.25));
  return sharp({
    create: { width: w, height: h, channels: 4, background: SURFACE },
  })
    .composite([{ input: icon, gravity: "center" }])
    .png()
    .toBuffer();
}

/**
 * iOS picks a launch image by exact logical size + pixel ratio, so the list is
 * one entry per device class — the modern set, portrait. A device that matches
 * nothing gets a plain white launch, which is the graceful fallback anyway.
 */
const SPLASHES = [
  [1290, 2796, 430, 932, 3], // 14 Pro Max, 15 Plus/Pro Max, 16 Plus
  [1320, 2868, 440, 956, 3], // 16 Pro Max
  [1206, 2622, 402, 874, 3], // 16 Pro
  [1179, 2556, 393, 852, 3], // 14 Pro, 15, 15 Pro, 16
  [1284, 2778, 428, 926, 3], // 12/13 Pro Max, 14 Plus
  [1170, 2532, 390, 844, 3], // 12/13/14, 16e
  [1125, 2436, 375, 812, 3], // X/XS/11 Pro, 12/13 mini
  [1242, 2688, 414, 896, 3], // XS Max, 11 Pro Max
  [828, 1792, 414, 896, 2], // XR, 11
  [750, 1334, 375, 667, 2], // 8, SE 2/3
  [2048, 2732, 1024, 1366, 2], // iPad Pro 12.9/13
  [1668, 2388, 834, 1194, 2], // iPad Pro 11
  [1640, 2360, 820, 1180, 2], // iPad Air 11
  [1620, 2160, 810, 1080, 2], // iPad 10.2/10.9
  [1536, 2048, 768, 1024, 2], // iPad 9.7, mini (older)
  [1488, 2266, 744, 1133, 2], // iPad mini 8.3
];

const out = async (file, buf) => {
  await mkdir(path.dirname(file), { recursive: true });
  await writeFile(file, buf);
  console.log("  wrote", path.relative(ROOT, file));
};

await out(`${BRAND}/icon-192.png`, await iconPng(192));
await out(`${BRAND}/icon-512.png`, await iconPng(512));
await out(`${BRAND}/icon-maskable-192.png`, await maskable(192));
await out(`${BRAND}/icon-maskable-512.png`, await maskable(512));
await out(`${BRAND}/apple-touch-icon.png`, await iconPng(180));

const descriptors = [];
for (const [w, h, dw, dh, dpr] of SPLASHES) {
  const name = `splash-${w}x${h}.png`;
  await out(`${BRAND}/splash/${name}`, await splash(w, h));
  descriptors.push(
    `  {\n    url: "/brand/splash/${name}",\n    media: "(device-width: ${dw}px) and (device-height: ${dh}px) and (-webkit-device-pixel-ratio: ${dpr}) and (orientation: portrait)",\n  },`,
  );
}

await mkdir(`${ROOT}/src/lib/generated`, { recursive: true });
await writeFile(
  `${ROOT}/src/lib/generated/startup-images.ts`,
  `// GENERATED by scripts/generate-brand-assets.mjs — edit that, not this.
export const STARTUP_IMAGES = [
${descriptors.join("\n")}
] as const;
`,
);
console.log("  wrote src/lib/generated/startup-images.ts");
